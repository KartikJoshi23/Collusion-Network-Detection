def _between(text: str, start: str, end: str) -> str:
    i = text.index(start) + len(start)
    return text[i : text.index(end, i)]


def convert(source: str) -> str:
    """Return the sn-jnl manuscript for the IEEE manuscript ``source``."""
    src = source.replace("\r\n", "\n")
    title = re.sub(r"\\\\\s*", " ", _between(src, r"\title{", "}\n")).strip()
    abstract = _between(src, r"\begin{abstract}", r"\end{abstract}").strip("\n")
    keywords = _between(src, r"\begin{IEEEkeywords}", r"\end{IEEEkeywords}").strip()
    keywords = keywords.rstrip(".")
    body = _between(src, r"\end{IEEEkeywords}", r"\section*{Acknowledgements}")
    acknowledgements = _between(src, r"\section*{Acknowledgements}", r"\appendices").strip()
    appendices = _between(src, r"\appendices", r"\begin{thebibliography}")

    def tidy(part: str) -> str:
        part = re.sub(r"(\\includegraphics(?:\[[^\]]*\])?\{)figures/", r"\1", part)
        # The iicol column is about 50pt narrower than an IEEE column, and its
        # Computer Modern type is wider than Times, so most tables would overrun
        # the column. Every table therefore spans the page, and a tabular still
        # wider than the line is scaled down to fit it. (sn-jnl wraps a
        # single-column table in threeparttable, which cannot hold the scaling
        # box, so spanning is also what makes the scaling possible.)
        part = re.sub(r"\\begin\{table\}(?:\[[^\]]*\])?", r"\\begin{table*}[tp]", part)
        part = part.replace(r"\end{table}", r"\end{table*}")
        part = part.replace(
            "\\begin{tabular}", "\\begin{adjustbox}{max width=\\linewidth}\n\\begin{tabular}"
        )
        part = part.replace("\\end{tabular}", "\\end{tabular}\n\\end{adjustbox}")
        return part.replace("\\balance\n", "")

    body, appendices = tidy(body), tidy(appendices)
    acknowledgements = re.sub(
        r"^\[Placeholder (?:---|--|-) (.*)\]$",
        r"\\AUTHORS{Placeholder: \1}",
        acknowledgements,
        flags=re.S,
    )

    front = [f"\\title[One Stack, Two Ledgers]{{{title}}}", ""]
    for i, (first, last, mail) in enumerate(AUTHORS):
        star = "*" if i == 0 else ""
        front.append(f"\\author{star}[1]{{\\fnm{{{first}}} \\sur{{{last}}}}}\\email{{{mail}}}")
    front += [
        "",
        r"\affil*[1]{\orgname{SP Jain School of Global Management},"
        r" \orgaddress{\city{Dubai}, \country{United Arab Emirates}}}",
        "",
        f"\\abstract{{{abstract}}}",
        "",
        f"\\keywords{{{keywords}}}",
        "",
        r"\maketitle",
    ]
    out = (
        PREAMBLE
        + "\n".join(front)
        + "\n"
        + body.rstrip("\n")
        + "\n\n\\backmatter\n\n\\bmhead{Acknowledgements}\n"
        + acknowledgements
        + "\n\n"
        + DECLARATIONS
        + "\n\\begin{appendices}\n"
        # sn-jnl numbers appendix tables A1, C2, ... across appendices; restart
        # the count in each appendix so that Appendix C opens with Table C1
        + "\\counterwithin*{table}{section}\n"
        + appendices.strip("\n")
        + "\n\n\\end{appendices}\n\n\\bibliography{references}\n\n\\end{document}\n"
    )
    leftover = sorted(set(re.findall(r"\\IEEE\w+|IEEEkeywords|thebibliography|\\bibitem", out)))
    if leftover:
        raise ValueError(f"IEEE-only markup left in the Springer version: {leftover}")
    return out


SUPPORT = ("references.bib", "sn-jnl.cls", "sn-mathphys-num.bst", "cuted.sty")


def bundle(target: Path) -> tuple[Path, Path]:
    """Flat upload folder, compiled in place, and a zip of its sources and .bbl.

    Returns the compiled PDF and the zip. The PDF is a check that the folder the
    journal receives compiles on its own; it is not part of the upload."""
    out = PAPER / "build" / "springer_upload"
    if out.exists():
        shutil.rmtree(out)
    out.mkdir(parents=True)
    tex = target.read_text(encoding="utf-8")
    figures = re.findall(r"\\includegraphics(?:\[[^\]]*\])?\{([^}]+)\}", tex)
    sources = [target, *(PAPER / name for name in SUPPORT)]
    sources += [PAPER / "figures" / name for name in figures]
    for f in sources:
        shutil.copy2(f, out / f.name)
    subprocess.run(
        ["latexmk", "-pdf", "-interaction=nonstopmode", "-halt-on-error", target.name],
        cwd=out,
        check=True,
        capture_output=True,
    )
    keep = [out / f.name for f in sources] + [out / (target.stem + ".bbl")]
    archive = out.with_suffix(".zip")
    with zipfile.ZipFile(archive, "w", zipfile.ZIP_DEFLATED) as z:
        for f in keep:
            z.write(f, f.name)
    return out / (target.stem + ".pdf"), archive


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--bundle", action="store_true", help="also build the flat upload folder")
    args = parser.parse_args()
    TARGET.write_text(convert(SOURCE.read_text(encoding="utf-8")), encoding="utf-8", newline="\n")
    print(f"wrote {TARGET.relative_to(REPO)}")
    if args.bundle:
        pdf, archive = bundle(TARGET)
        print(f"compiled {pdf.relative_to(REPO)}")
        print(f"wrote {archive.relative_to(REPO)}")
    return 0


