"""Build the Springer Nature (sn-jnl) version of the paper from the IEEE source.

``paper/collusiongraph_paper.tex`` stays the single source of content. This
script rewrites its preamble, front matter and back matter for the Springer
Nature template (two-column ``iicol`` layout and the numbered Math and Physical
Sciences reference style, as the International Journal of Data Science and
Analytics asks) and writes ``paper/collusiongraph_paper_springer.tex``. A unit
test regenerates the file and fails if the committed copy differs, so the two
versions cannot drift.

Usage::

    uv run python scripts/paper_to_springer.py            # write the Springer .tex
    uv run python scripts/paper_to_springer.py --bundle   # and the flat upload folder

``--bundle`` copies the .tex, the bibliography, the class, style and package
files and the figures into ``paper/build/springer_upload/`` with no subfolders,
as IJDSA's submission system requires. It then compiles the folder with latexmk
there, exactly as the journal will, and zips the sources with the .bbl.
"""

